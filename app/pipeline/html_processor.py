import re


# ============================================================
# 1. تقسیم متن به جمله‌ها
# ============================================================

def split_sentences(text):
    """
    متن را به جمله‌های جداگانه تقسیم می‌کند.

    هنگام تقسیم جمله‌ها، موارد زیر به عنوان پایان جمله
    در نظر گرفته نمی‌شوند:

        Mr.
        Mrs.
        Ms.
        Dr.
        Prof.
        Sr.
        Jr.
        etc.
        vs.
        e.g.
        i.e.
        viz.
        cf.
        Ch.
        p.
        pp.
        vol.
        ex.
        no.

    همچنین اعداد اعشاری مانند:

        3.14
        10.5
        2026.8

    باعث شکستن جمله نمی‌شوند.

    روش پیاده‌سازی:
        به جای استفاده از look-behind با طول متغیر،
        ابتدا نقاطی که نباید باعث Split شوند با یک
        Placeholder موقت جایگزین می‌شوند.

        سپس جمله‌ها Split می‌شوند.

        در پایان Placeholderها دوباره به نقطه تبدیل می‌شوند.

    این روش با Python re سازگار است و خطای:

        PatternError: look-behind requires fixed-width pattern

    ایجاد نمی‌کند.
    """

    # --------------------------------------------------------
    # بررسی ورودی
    # --------------------------------------------------------

    if not text:
        return []

    # اطمینان از اینکه ورودی String است.
    text = str(text)

    # --------------------------------------------------------
    # Placeholder موقت
    # --------------------------------------------------------
    #
    # این مقدار باید بسیار بعید باشد که در متن واقعی کتاب
    # وجود داشته باشد.
    #
    # اگر نقطه‌ای مربوط به abbreviation یا decimal باشد،
    # موقتاً با این Placeholder جایگزین می‌شود.
    # --------------------------------------------------------

    DOT_PLACEHOLDER = "___BOOKTRANSLATE_DOT___"

    # --------------------------------------------------------
    # 1. محافظت از اختصارات
    # --------------------------------------------------------
    #
    # ترتیب مهم است.
    #
    # ابتدا e.g. و i.e. را جداگانه پردازش می‌کنیم چون
    # بیشتر از یک نقطه دارند.
    # --------------------------------------------------------

    protected_abbreviations = [
        "Mr.",
        "Mrs.",
        "Ms.",
        "Dr.",
        "Prof.",
        "Sr.",
        "Jr.",
        "etc.",
        "vs.",
        "e.g.",
        "i.e.",
        "viz.",
        "cf.",
        "Ch.",
        "p.",
        "pp.",
        "vol.",
        "ex.",
        "no.",
    ]

    # --------------------------------------------------------
    # جایگزینی اختصارات
    # --------------------------------------------------------

    for abbreviation in protected_abbreviations:

        # re.escape باعث می‌شود نقطه به عنوان کاراکتر واقعی
        # در نظر گرفته شود، نه wildcard در regex.
        pattern = re.escape(abbreviation)

        text = re.sub(
            pattern,
            abbreviation.replace(".", DOT_PLACEHOLDER),
            text,
            flags=re.IGNORECASE,
        )

    # --------------------------------------------------------
    # 2. محافظت از اعداد اعشاری
    # --------------------------------------------------------
    #
    # مثال:
    #
    # 3.14
    # 10.5
    # 2026.8
    #
    # نقطه بین دو رقم نباید باعث Split شود.
    # --------------------------------------------------------

    text = re.sub(
        r"(?<=\d)\.(?=\d)",
        DOT_PLACEHOLDER,
        text,
    )

    # --------------------------------------------------------
    # 3. تقسیم جمله‌ها
    # --------------------------------------------------------
    #
    # اکنون دیگر نیازی به look-behind متغیر نداریم.
    #
    # جمله زمانی Split می‌شود که:
    #
    #   .
    #
    # سپس یک یا چند Space وجود داشته باشد
    #
    # و بعد از Space یک حرف بزرگ انگلیسی بیاید.
    #
    # مثال:
    #
    # This is a sentence. This is another sentence.
    #
    # --------------------------------------------------------

    sentences = re.split(
        r"\.\s+(?=[A-Z])",
        text,
    )

    # --------------------------------------------------------
    # 4. برگرداندن نقاط محافظت‌شده
    # --------------------------------------------------------

    restored_sentences = []

    for sentence in sentences:

        # Placeholder را دوباره به نقطه تبدیل می‌کنیم.
        sentence = sentence.replace(
            DOT_PLACEHOLDER,
            ".",
        )

        sentence = sentence.strip()

        if sentence:
            restored_sentences.append(sentence)

    # --------------------------------------------------------
    # 5. اضافه کردن نقطه به جمله‌هایی که با نقطه Split شده‌اند
    # --------------------------------------------------------
    #
    # re.split() خود نقطه را حذف می‌کند.
    #
    # بنابراین برای همه جمله‌ها به جز آخرین بخش،
    # نقطه را برمی‌گردانیم.
    #
    # اگر متن اصلی قبل از Split با نقطه تمام شده باشد،
    # بخش آخر ممکن است خودش نقطه نداشته باشد.
    # --------------------------------------------------------

    final_sentences = []

    for index, sentence in enumerate(restored_sentences):

        # اگر این آخرین جمله نیست، نقطه پایان را اضافه می‌کنیم.
        if index < len(restored_sentences) - 1:

            if not sentence.endswith("."):
                sentence += "."

        final_sentences.append(sentence)

    return final_sentences


