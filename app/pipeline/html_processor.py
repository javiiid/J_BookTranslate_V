# 2. تقسیم HTML به Paragraph و Chunk
# ============================================================

def split_html_by_paragraph(
    html_str,
    max_chunk_size=10000
):
    """
    محتوای HTML را ابتدا بر اساس Paragraph تقسیم می‌کند
    و سپس در صورت نیاز Paragraphهای بزرگ را بر اساس جمله
    به Chunkهای کوچک‌تر تقسیم می‌کند.

    Parameters
    ----------
    html_str : str
        محتوای HTML

    max_chunk_size : int
        حداکثر اندازه مجاز هر Chunk

    Returns
    -------
    list
        لیستی از Chunkهای HTML
    """

    # ========================================================
    # 1. بررسی ورودی
    # ========================================================

    if not html_str:
        return []

    html_str = str(html_str)

    # ========================================================
    # 2. تقسیم HTML بر اساس </p>
    # ========================================================

    paragraphs = html_str.split("</p>")

    # ========================================================
    # 3. پاک‌سازی Paragraphها
    # ========================================================

    paragraphs = [
        p.strip() + "</p>"
        for p in paragraphs
        if p.strip()
    ]

    # ========================================================
    # 4. متغیرهای اصلی
    # ========================================================

    chunks = []

    current_chunk = ""

    # ========================================================
    # 5. پردازش Paragraphها
    # ========================================================

    for paragraph in paragraphs:

        # ====================================================
        # بررسی اینکه Paragraph داخل Chunk فعلی جا می‌شود
        # یا خیر
        # ====================================================

        if (
            len(current_chunk) + len(paragraph)
            > max_chunk_size
        ):

            # ==================================================
            # حالت اول:
            # Chunk فعلی خالی نیست.
            # ==================================================

            if current_chunk:

                # Chunk فعلی را ذخیره می‌کنیم.
                chunks.append(current_chunk)

                # Paragraph فعلی شروع Chunk جدید می‌شود.
                current_chunk = paragraph

            # ==================================================
            # حالت دوم:
            # Chunk فعلی خالی است.
            #
            # یعنی خود Paragraph بزرگ‌تر از max_chunk_size
            # است.
            # ==================================================

            else:

                # ------------------------------------------------
                # Paragraph بزرگ را به جمله‌ها تقسیم می‌کنیم.
                # ------------------------------------------------

                sentences = split_sentences(paragraph)

                # ------------------------------------------------
                # Chunk موقت
                # ------------------------------------------------

                temp_chunk = ""

                # =================================================
                # پردازش جمله‌ها
                # =================================================

                for sentence in sentences:

                    # ------------------------------------------------
                    # بررسی اندازه Chunk
                    # ------------------------------------------------

                    if (
                        len(temp_chunk) + len(sentence)
                        > max_chunk_size
                    ):

                        # --------------------------------------------
                        # اگر Chunk فعلی چیزی دارد،
                        # آن را ذخیره می‌کنیم.
                        # --------------------------------------------

                        if temp_chunk:

                            chunks.append(temp_chunk)

                        # --------------------------------------------
                        # جمله فعلی شروع Chunk جدید می‌شود.
                        # --------------------------------------------

                        temp_chunk = sentence

                    else:

                        # --------------------------------------------
                        # اگر Chunk خالی نیست،
                        # قبل از جمله یک Space اضافه می‌کنیم.
                        # --------------------------------------------

                        if temp_chunk:

                            temp_chunk += " "

                        # --------------------------------------------
                        # اضافه کردن جمله
                        # --------------------------------------------

                        temp_chunk += sentence

                # =================================================
                # ذخیره آخرین Chunk موقت
                # =================================================

                if temp_chunk:

                    chunks.append(temp_chunk)

                # ------------------------------------------------
                # چون Paragraph بزرگ به صورت کامل پردازش شد،
                # Chunk فعلی را خالی می‌کنیم.
                # ------------------------------------------------

                current_chunk = ""

        # ====================================================
        # Paragraph در اندازه مجاز است.
        # ====================================================

        else:

            # ------------------------------------------------
            # اگر Chunk فعلی خالی نیست،
            # بین Paragraphها یک Space قرار می‌دهیم.
            # ------------------------------------------------

            if current_chunk:

                current_chunk += " "

            # ------------------------------------------------
            # اضافه کردن Paragraph
            # ------------------------------------------------

            current_chunk += paragraph

    # ========================================================
    # 6. ذخیره آخرین Chunk
    # ========================================================

    if current_chunk:

        chunks.append(current_chunk)

    # ========================================================
    # 7. خروجی نهایی
    # ========================================================

    return chunks